import matplotlib.pyplot as plt
import numpy as np
from matplotlib import patches
from matplotlib.collections import LineCollection

from tactex.typing import Point2D, Ray2D


def show(rays: Ray2D, resolution: int, k: int = 3, cols: int = 3) -> None:
    """Plot the first k ray batches with their grid bounds and sampling circle.

    Generated by Gemini.

    Each batch element gets its own subplot showing the `[0, resolution]^2`
    grid box, the bounding sampling circle, the green `start` and red `end`
    points on the circumference, and the connecting ray segments.

    Args:
        rays: Array of shape `(B, N, 2, 2)` holding `N` rays per batch element.
        resolution: Grid resolution (side length of the square grid).
        k: Number of batch elements to display. Clipped to `B` if larger.
        cols: Number of subplot columns. Rows are `ceil(k / cols)`, and
            unused axes are hidden.

    Returns:
        None. The figure is displayed with `plt.show()`.
    """
    k = min(k, len(rays))
    cols = min(k, cols)
    rows: int = int(np.ceil(k / cols))
    fig, axs = plt.subplots(rows, cols, figsize=(4.5 * cols, 4.5 * rows), squeeze=False)

    radius: float = float((resolution / 2) * np.sqrt(2))

    for ax, batch_rays in zip(axs.flatten(), rays[:k]):
        start_points: Point2D = batch_rays[:, 0, :]
        end_points: Point2D = batch_rays[:, 1, :]

        grid_box: patches.Rectangle = patches.Rectangle(
            (0, 0),
            resolution,
            resolution,
            linewidth=1.5,
            edgecolor="black",
            facecolor="none",
            linestyle="--",
            label="Grid",
        )
        ax.add_patch(grid_box)

        circle: patches.Circle = patches.Circle(
            (resolution / 2, resolution / 2),
            radius,
            linewidth=1.5,
            edgecolor="gray",
            facecolor="none",
            label="Circle",
        )
        ax.add_patch(circle)

        line_collection = LineCollection(
            batch_rays, colors="tab:blue", alpha=0.4, linewidths=1.0
        )
        ax.add_collection(line_collection)
        ax.scatter(
            start_points[:, 0],
            start_points[:, 1],
            color="tab:green",
            s=25,
            zorder=3,
            label="Start",
        )
        ax.scatter(
            end_points[:, 0],
            end_points[:, 1],
            color="tab:red",
            s=25,
            zorder=3,
            label="End",
        )
        ax.set_aspect("equal")
        ax.grid(True, alpha=0.3)

    axs.flatten()[0].legend(loc="upper right")
    for ax in axs.flatten()[k:]:
        ax.axis("off")

    fig.tight_layout()
    plt.show()
