import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import ListedColormap

from tactex.typing import OccupancyGrid2D, TraversalGrid2D


def show(
    traversal_grids: TraversalGrid2D,
    occupancy_grids: OccupancyGrid2D | None = None,
    k: int = 3,
) -> None:
    """Plot the first k traversal grids, optionally paired with ground-truth occupancy grids.

    Generated by Gemini.

    Converts the 3-channel `[occupied, free, unknown]` traversal grid into a
    color-coded 2D map (red = occupied, blue = free, gray = unknown). When
    `occupancy_grids` is provided, a second row is plotted directly underneath
    showing the corresponding ground-truth binary occupancy grids.

    Args:
        traversal_grids: Array of shape `(B, 3, H, W)` with boolean or binary
            channels `[occupied, free, unknown]`.
        occupancy_grids: Optional ground-truth occupancy array of shape
            `(B, H, W)` to display in a bottom comparison row.
        k: Number of batch elements to display. Clipped to `B` if larger.

    Returns:
        None. The figure is displayed with `plt.show()`.
    """
    b, _, h, w = traversal_grids.shape
    k = min(k, b)

    # 0 = unknown (gray), 1 = free (blue), 2 = occupied (red)
    state_grid: np.ndarray = np.zeros((k, h, w), dtype=np.int32)
    state_grid[traversal_grids[:k, 1].astype(np.bool)] = 1
    state_grid[traversal_grids[:k, 0].astype(np.bool)] = 2

    cmap = ListedColormap(["#efefef", "#1f77b4", "#ff1a1a"])

    rows: int = 2 if occupancy_grids is not None else 1
    fig, axes = plt.subplots(rows, k, figsize=(4.0 * k, 4.0 * rows), squeeze=False)

    for i in range(k):
        ax = axes[0, i]
        ax.imshow(
            state_grid[i].T,
            origin="lower",
            extent=(0, h, 0, w),
            cmap=cmap,
            vmin=0,
            vmax=2,
            interpolation="nearest",
        )
        ax.set_title(f"Traversal Grid {i}")
        ax.set_aspect("equal")

        if occupancy_grids is not None:
            ax_gt = axes[1, i]
            ax_gt.imshow(
                occupancy_grids[i].T,
                origin="lower",
                extent=(0, h, 0, w),
                cmap="binary",
                vmin=0,
                vmax=1,
                interpolation="nearest",
            )
            ax_gt.set_title(f"Ground Truth {i}")
            ax_gt.set_aspect("equal")

    axes[0, -1].legend(
        handles=[
            mpatches.Patch(color="#ff1a1a", label="Occupied"),
            mpatches.Patch(color="#1f77b4", label="Free"),
            mpatches.Patch(color="#efefef", label="Unknown"),
        ],
        loc="upper right",
    )
    fig.tight_layout()
    plt.show()
