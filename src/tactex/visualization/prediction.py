import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import numpy as np
import torch
from matplotlib.colors import ListedColormap
from torch import nn

from tactex.typing import OccupancyGrid2D, TraversalGrid2D


@torch.no_grad()
def show(
    model: nn.Module,
    traversal_grids: TraversalGrid2D,
    occupancy_grids: OccupancyGrid2D,
    k: int = 3,
    threshold: float = 0.5,
    device: torch.device | str | None = None,
) -> None:
    """Plot model predictions against ground-truth occupancy grids.

    Generated by Gemini.

    For each of the first k samples, shows four rows:
    input traversal grid, predicted occupancy probability, thresholded
    prediction, and the error map vs. ground truth (TP / FP / FN / TN).

    Args:
        model: Model mapping `(B, 3, H, W)` inputs to `(B, 1, H, W)` logits.
        traversal_grids: Array of shape `(B, 3, H, W)` with channels
            `[occupied, free, unknown]`.
        occupancy_grids: Ground-truth array of shape `(B, H, W)` or `(B, 1, H, W)`.
        k: Number of samples to display. Clipped to `B`.
        threshold: Probability threshold for binarizing predictions.
        device: Device to run the model on. Defaults to the model's device.
    """
    traversal_grids = np.asarray(traversal_grids)
    gt: np.ndarray = np.asarray(occupancy_grids).astype(bool)
    if gt.ndim == 4:
        gt = gt[:, 0]
    k = min(k, traversal_grids.shape[0])

    if device is None:
        device = next(model.parameters()).device
    was_training: bool = model.training
    model.eval()
    x = torch.from_numpy(traversal_grids[:k]).to(device, torch.float32)
    probs: np.ndarray = torch.sigmoid(model(x))[:, 0].cpu().numpy()
    model.train(was_training)

    pred: np.ndarray = probs >= threshold
    gt = gt[:k]

    # Input: 0 = unknown, 1 = free, 2 = occupied
    state = np.zeros(pred.shape, dtype=np.int32)
    state[traversal_grids[:k, 1].astype(bool)] = 1
    state[traversal_grids[:k, 0].astype(bool)] = 2
    input_cmap = ListedColormap(["#efefef", "#1f77b4", "#ff1a1a"])

    # Error: 0 = TN, 1 = TP, 2 = FP, 3 = FN
    error = np.zeros(pred.shape, dtype=np.int32)
    error[pred & gt] = 1
    error[pred & ~gt] = 2
    error[~pred & gt] = 3
    error_cmap = ListedColormap(["#ffffff", "#000000", "#ff7f0e", "#9467bd"])

    fig, axes = plt.subplots(5, k, figsize=(3.5 * k, 14.0), squeeze=False)
    for i in range(k):
        iou = (pred[i] & gt[i]).sum() / max((pred[i] | gt[i]).sum(), 1)
        panels = [
            (gt[i], "binary", 0, 1, f"Ground truth {i}"),
            (state[i], input_cmap, 0, 2, f"Input {i}"),
            (probs[i], "viridis", 0, 1, f"Probability {i}"),
            (pred[i], "binary", 0, 1, f"Prediction {i}"),
            (error[i], error_cmap, 0, 3, f"Error {i} (IoU {iou:.2f})"),
        ]
        for row, (img, cmap, vmin, vmax, title) in enumerate(panels):
            ax = axes[row, i]
            im = ax.imshow(
                img.T,
                origin="lower",
                cmap=cmap,
                vmin=vmin,
                vmax=vmax,
                interpolation="nearest",
            )
            ax.set_title(title)
            ax.set_aspect("equal")
            if row == 1 and i == k - 1:
                fig.colorbar(im, ax=ax, fraction=0.046)

    axes[0, -1].legend(
        handles=[
            mpatches.Patch(color="#ff1a1a", label="Occupied"),
            mpatches.Patch(color="#1f77b4", label="Free"),
            mpatches.Patch(color="#efefef", label="Unknown"),
        ],
        loc="upper right",
        fontsize="small",
    )
    axes[3, -1].legend(
        handles=[
            mpatches.Patch(color="#000000", label="TP"),
            mpatches.Patch(color="#ff7f0e", label="FP"),
            mpatches.Patch(color="#9467bd", label="FN"),
        ],
        loc="upper right",
        fontsize="small",
    )
    fig.tight_layout()
    plt.show()
