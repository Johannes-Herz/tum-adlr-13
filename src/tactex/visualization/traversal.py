import matplotlib.pyplot as plt
import numpy as np
from matplotlib.collections import LineCollection

from tactex.typing import Ray2D, Traversal2D


def show(
    traversals: Traversal2D,
    resolution: int,
    rays: Ray2D | None = None,
    k: int = 3,
    cols: int = 3,
) -> None:
    """Plot the rasterized grid cells of the first k ray traversal batches.

    Generated by Gemini.

    Each batch element gets its own subplot showing the `[0, resolution]^2`
    grid with traversed cells highlighted in blue. If `rays` is provided, the
    continuous ray segments are overlaid on top of the rasterized cells.

    Args:
        traversals: Array of shape `(B, N, M, 2)` holding integer `(ix, iy)`
            grid coordinates along `N` rays per batch element.
        resolution: Grid resolution (side length of the square grid).
        rays: Optional array of shape `(B, N, 2, 2)` holding the continuous
            `[start, end]` ray segments to overlay on each subplot.
        k: Number of batch elements to display. Clipped to `B` if larger.
        cols: Number of subplot columns. Rows are `ceil(k / cols)`, and
            unused axes are hidden.

    Returns:
        None. The figure is displayed with `plt.show()`.
    """
    k = min(k, len(traversals))
    cols = min(k, cols)
    rows: int = int(np.ceil(k / cols))
    fig, axs = plt.subplots(rows, cols, figsize=(4.5 * cols, 4.5 * rows), squeeze=False)

    cell_ticks: np.ndarray = np.arange(0, resolution + 1, 1)

    for i, (ax, batch_traversals) in enumerate(zip(axs.flatten(), traversals[:k])):
        grid: np.ndarray = np.zeros((resolution, resolution), dtype=np.int32)
        in_bounds: np.ndarray = (batch_traversals >= 0).all(axis=-1) & (
            batch_traversals < resolution
        ).all(axis=-1)
        valid: np.ndarray = batch_traversals[in_bounds]
        grid[valid[:, 1], valid[:, 0]] = 1

        ax.imshow(
            grid,
            origin="lower",
            extent=(0, resolution, 0, resolution),
            cmap="Blues",
            vmin=0,
            vmax=1.5,
            interpolation="nearest",
        )

        if rays is not None:
            ax.add_collection(
                LineCollection(rays[i], colors="black", linewidths=1.2, alpha=0.8)
            )

        ax.set_xticks(cell_ticks, minor=True)
        ax.set_yticks(cell_ticks, minor=True)
        ax.grid(True, which="both", color="lightgray", linewidth=0.5)
        ax.set_xlim(0, resolution)
        ax.set_ylim(0, resolution)
        ax.set_aspect("equal")

    for ax in axs.flatten()[k:]:
        ax.axis("off")

    fig.tight_layout()
    plt.show()
